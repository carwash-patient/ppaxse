-- 2026-11-09d 한마디 기프티콘 주간 추첨 (응모번호 방식, 가입 없이도 응모)
-- 여러 번 실행해도 안전합니다.
--
--  · 응모 기간: 매주 토요일 0시 ~ 금요일 24시 (한국 시간). 추첨은 다음 주 월요일.
--  · 첫 회차: 2026-11-14(토) ~ 11-20(금), 11-23(월) 추첨
--  · 응모 조건: 한마디 10자 이상 + 같은 세차장에 정보 제보 또는 '다녀왔어요/정보가 맞아요' 확인을 함께 남김
--  · 한 사람(기기·계정)당 한 주에 1번만 응모 (여러 개 써도 응모는 1번)
--  · 응모하면 응모번호(예: A7K-2Q9)가 나오고, 그 사람에게만 보임 → 당첨 확인 수단
--  · 매주 '누구나 추첨' 2명 + '회원 추첨' 2명. 회원은 두 추첨 모두 참여(기회 2번), 한 사람이 두 번 당첨되지는 않음
--  · 운영자가 한마디를 숨기거나 사람을 막으면 그 응모는 추첨에서 빠짐
--  · 같은 기기는 같은 세차장에 한마디를 한 달에 1번만 남길 수 있음 (도배 방지)
--  · 개인정보: 응모에는 연락처를 받지 않음. 당첨자만 이메일로 응모번호와 받을 번호를 보냄

-- ── 주 계산: 그 시각이 속한 주의 토요일 (한국 시간) ──
create or replace function public.ppx_event_week(t timestamptz default now())
returns date language sql stable as $$
  select d - ((extract(dow from d)::int + 1) % 7)
  from (select (t at time zone 'Asia/Seoul')::date as d) x
$$;
create or replace function public.ppx_event_start()
returns date language sql immutable as $$ select date '2026-11-14' $$;

-- ── 응모 ──
create table if not exists public.event_entries (
  id          bigint generated by default as identity primary key,
  week        date not null,
  user_id     uuid not null references public.profiles(id) on delete cascade,
  comment_id  bigint references public.place_comments(id) on delete set null,
  code        text not null unique,
  created_at  timestamptz not null default now(),
  unique (week, user_id)
);
create index if not exists event_entries_week_idx on public.event_entries (week);

create table if not exists public.event_winners (
  week        date not null,
  entry_id    bigint not null references public.event_entries(id) on delete cascade,
  pool        text not null check (pool in ('member', 'all')),
  created_at  timestamptz not null default now(),
  primary key (week, entry_id)
);

alter table public.event_entries enable row level security;
alter table public.event_winners enable row level security;
drop policy if exists "entries: 본인·운영자 조회" on public.event_entries;
create policy "entries: 본인·운영자 조회" on public.event_entries
  for select to authenticated using (user_id = (select auth.uid()) or (select public.is_admin()));
drop policy if exists "winners: 운영자 조회" on public.event_winners;
create policy "winners: 운영자 조회" on public.event_winners
  for select to authenticated using ((select public.is_admin()));
-- 쓰기는 아래 함수로만
revoke all on public.event_entries from anon, authenticated;
revoke all on public.event_winners from anon, authenticated;
grant select on public.event_entries to authenticated;
grant select on public.event_winners to authenticated;

-- 회원인지 (이메일로 가입한 계정)
create or replace function public.ppx_is_member(u uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from auth.users x
                 where x.id = u and coalesce(x.is_anonymous, false) = false and x.email is not null)
$$;
revoke all on function public.ppx_is_member(uuid) from public, anon, authenticated;

-- 추첨에 들어가는 응모인지 (한마디가 숨겨지지 않았고, 막힌 사람·운영자가 아님)
create or replace function public.ppx_entry_valid(e public.event_entries)
returns boolean language sql stable security definer set search_path = public as $$
  select e.comment_id is not null
     and exists (select 1 from public.place_comments c where c.id = e.comment_id and not c.hidden)
     and not exists (select 1 from public.profiles p where p.id = e.user_id and (p.blocked or p.role = 'admin'))
$$;
revoke all on function public.ppx_entry_valid(public.event_entries) from public, anon, authenticated;

-- 응모하기: 한마디를 저장한 직후 화면이 부름
create or replace function public.ppx_enter_event(cid bigint)
returns json language plpgsql security definer set search_path = public as $$
declare
  v uuid := auth.uid();
  w date := public.ppx_event_week(now());
  c public.place_comments;
  e public.event_entries;
  chars text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  k text; i int;
begin
  if v is null then raise exception '이용자 확인이 필요해요.'; end if;
  if (now() at time zone 'Asia/Seoul')::date < public.ppx_event_start() then
    raise exception '기프티콘 추첨은 11월 14일(토)부터 응모할 수 있어요.';
  end if;
  if exists (select 1 from public.profiles where id = v and (blocked or role = 'admin')) then
    raise exception '이 계정은 추첨에 응모할 수 없어요.';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(v::text || ':event', 0));

  -- 이번 주에 이미 응모했으면 그 번호를 돌려줌
  select * into e from public.event_entries where week = w and user_id = v;
  if found then
    return json_build_object('code', e.code, 'week', w, 'already', true);
  end if;

  select * into c from public.place_comments where id = cid and user_id = v and not hidden;
  if not found then raise exception '응모할 한마디를 찾지 못했어요.'; end if;
  if c.created_at < now() - interval '2 hours' or public.ppx_event_week(c.created_at) <> w then
    raise exception '이번 주에 남긴 한마디로만 응모할 수 있어요.';
  end if;
  if char_length(c.body) < 10 then
    raise exception '응모하려면 한마디를 10자 이상 써 주세요.';
  end if;
  if not exists (select 1 from public.place_reports r
                 where r.reporter = v and r.place_id = c.place_id and r.created_at > c.created_at - interval '2 hours')
     and not exists (select 1 from public.place_checks k2
                 where k2.user_id = v and k2.place_id = c.place_id and k2.created_at > c.created_at - interval '2 hours') then
    raise exception '응모하려면 다녀온 시기나 세차장 정보를 하나 이상 함께 알려 주세요.';
  end if;

  for i in 1..20 loop
    k := '';
    for j in 1..6 loop k := k || substr(chars, 1 + floor(random() * 32)::int, 1); end loop;
    k := substr(k, 1, 3) || '-' || substr(k, 4, 3);
    exit when not exists (select 1 from public.event_entries where code = k);
  end loop;

  insert into public.event_entries (week, user_id, comment_id, code) values (w, v, c.id, k) returning * into e;
  return json_build_object('code', e.code, 'week', w, 'already', false);
end $$;
revoke all on function public.ppx_enter_event(bigint) from public, anon;
grant execute on function public.ppx_enter_event(bigint) to authenticated;

-- 누구나 볼 수 있는 현황: 이번 주 참여 수(실제 숫자), 지난 회차 당첨 번호, 내 응모번호
create or replace function public.ppx_event_status()
returns json language plpgsql stable security definer set search_path = public as $$
declare
  v uuid := auth.uid();
  w date := greatest(public.ppx_event_week(now()), public.ppx_event_start());
  lw date;
begin
  select max(week) into lw from public.event_winners;
  return json_build_object(
    'start', public.ppx_event_start(),
    'week', w, 'week_end', w + 6, 'draw_date', w + 9,
    'all_count',    (select count(*) from public.event_entries e where e.week = w and public.ppx_entry_valid(e)),
    'member_count', (select count(*) from public.event_entries e where e.week = w and public.ppx_entry_valid(e) and public.ppx_is_member(e.user_id)),
    'winners_all', 2, 'winners_member', 2,
    'last', case when lw is null then null else json_build_object(
      'week', lw,
      'all_count',    (select count(*) from public.event_entries e where e.week = lw and public.ppx_entry_valid(e)),
      'member_count', (select count(*) from public.event_entries e where e.week = lw and public.ppx_entry_valid(e) and public.ppx_is_member(e.user_id)),
      'winners', (select json_agg(json_build_object('code', e.code, 'pool', x.pool) order by x.pool desc, e.code)
                  from public.event_winners x join public.event_entries e on e.id = x.entry_id where x.week = lw)
    ) end,
    'mine', case when v is null then '[]'::json else coalesce((
      select json_agg(json_build_object('week', e.week, 'code', e.code,
                      'won', (select x.pool from public.event_winners x where x.entry_id = e.id)) order by e.week desc)
      from (select * from public.event_entries where user_id = v order by week desc limit 6) e), '[]'::json) end,
    'member', case when v is null then false else public.ppx_is_member(v) end
  );
end $$;
revoke all on function public.ppx_event_status() from public;
grant execute on function public.ppx_event_status() to anon, authenticated;

-- 운영자: 한 주의 응모 목록
create or replace function public.admin_event_week(w date)
returns table (entry_id bigint, code text, created_at timestamptz, is_member boolean, nickname text, email text,
               place_name text, body text, valid boolean, won text)
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception '운영자만 볼 수 있어요'; end if;
  return query
    select e.id, e.code, e.created_at, public.ppx_is_member(e.user_id),
           coalesce(pr.nickname, c.nickname), case when public.ppx_is_member(e.user_id) then u.email::text end,
           pl.name, c.body, public.ppx_entry_valid(e),
           (select x.pool from public.event_winners x where x.entry_id = e.id)
    from public.event_entries e
    left join public.profiles pr on pr.id = e.user_id
    left join auth.users u on u.id = e.user_id
    left join public.place_comments c on c.id = e.comment_id
    left join public.places pl on pl.id = c.place_id
    where e.week = w
    order by e.created_at;
end $$;
revoke all on function public.admin_event_week(date) from public, anon;
grant execute on function public.admin_event_week(date) to authenticated;

-- 운영자: 추첨 (회원 추첨 먼저, 그다음 남은 사람 중 누구나 추첨). 이미 뽑았으면 그대로 돌려줌
create or replace function public.admin_event_draw(w date, redraw boolean default false)
returns json language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception '운영자만 할 수 있어요'; end if;
  if w + 6 >= (now() at time zone 'Asia/Seoul')::date then
    raise exception '응모 기간(금요일)이 끝난 다음에 추첨할 수 있어요.';
  end if;
  perform pg_advisory_xact_lock(hashtextextended('event-draw:' || w::text, 0));
  if redraw then delete from public.event_winners where week = w; end if;
  if not exists (select 1 from public.event_winners where week = w) then
    insert into public.event_winners (week, entry_id, pool)
      select w, e.id, 'member' from public.event_entries e
      where e.week = w and public.ppx_entry_valid(e) and public.ppx_is_member(e.user_id)
      order by random() limit 2;
    insert into public.event_winners (week, entry_id, pool)
      select w, e.id, 'all' from public.event_entries e
      where e.week = w and public.ppx_entry_valid(e)
        and not exists (select 1 from public.event_winners x where x.week = w and x.entry_id = e.id)
      order by random() limit 2;
  end if;
  return (select coalesce(json_agg(json_build_object('code', e.code, 'pool', x.pool) order by x.pool desc), '[]'::json)
          from public.event_winners x join public.event_entries e on e.id = x.entry_id where x.week = w);
end $$;
revoke all on function public.admin_event_draw(date, boolean) from public, anon;
grant execute on function public.admin_event_draw(date, boolean) to authenticated;

-- ── 같은 세차장에는 한 달에 한마디 1번 (나머지는 11-09 규칙 그대로) ──
create or replace function public.place_comments_before_insert()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_uid uuid := auth.uid();
  v_request_role text := auth.jwt() ->> 'role';
begin
  if coalesce(v_request_role, '') not in ('anon', 'authenticated') then
    return new;
  end if;
  if v_uid is null then
    raise exception '한마디를 남기려면 먼저 이용자 확인이 필요해요.';
  end if;

  new.user_id := v_uid;
  new.hidden := false;
  new.created_at := now();
  new.body := btrim(new.body);
  new.nickname := nullif(btrim(coalesce(new.nickname, '')), '');

  perform pg_advisory_xact_lock(hashtextextended(v_uid::text, 0));
  perform public.ppx_guard('comment');

  if exists (
    select 1 from public.place_comments c
    where c.user_id = v_uid
      and c.created_at > now() - interval '30 seconds'
  ) then
    raise exception '한마디는 30초에 한 번씩 남길 수 있어요. 잠시 기다려 주세요.';
  end if;

  if exists (
    select 1 from public.place_comments c
    where c.user_id = v_uid
      and c.place_id = new.place_id
      and c.created_at > now() - interval '30 days'
  ) and not public.is_admin() then
    raise exception '이 세차장에는 이미 한마디를 남기셨어요. 같은 곳은 한 달에 한 번 남길 수 있어요.';
  end if;
  return new;
end;
$$;
revoke all on function public.place_comments_before_insert()
  from public, anon, authenticated;

-- ── 가입·로그인하면 이 기기로 한 응모도 계정으로 옮김 ──
create or replace function public.finish_claim(t uuid)
returns int language plpgsql security definer set search_path = public as $$
declare a uuid; n int := 0; k int;
begin
  if auth.uid() is null or coalesce((auth.jwt()->>'is_anonymous')::boolean, false) then return 0; end if;
  delete from public.anon_claims where token = t returning anon_id into a;
  if a is null or a = auth.uid() then return 0; end if;
  update public.places set submitted_by = auth.uid() where submitted_by = a;        get diagnostics k = row_count; n := n + k;
  update public.place_reports set reporter = auth.uid() where reporter = a;         get diagnostics k = row_count; n := n + k;
  update public.place_comments set user_id = auth.uid() where user_id = a;          get diagnostics k = row_count; n := n + k;
  -- 같은 날 같은 세차장을 두 번 확인한 기록은 하나만 남김
  delete from public.place_checks c where c.user_id = a and exists (
    select 1 from public.place_checks d where d.user_id = auth.uid() and d.place_id = c.place_id and d.created_on = c.created_on);
  update public.place_checks set user_id = auth.uid() where user_id = a;            get diagnostics k = row_count; n := n + k;
  -- 기프티콘 응모: 같은 주에 계정으로 이미 응모했으면 기기 쪽 응모는 정리 (한 주 1번)
  delete from public.event_entries e where e.user_id = a and exists (
    select 1 from public.event_entries d where d.user_id = auth.uid() and d.week = e.week);
  update public.event_entries set user_id = auth.uid() where user_id = a;           get diagnostics k = row_count; n := n + k;
  return n;
end $$;
revoke execute on function public.finish_claim(uuid) from anon;
