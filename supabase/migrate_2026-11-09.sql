-- 2026-11-09 빡세 한마디 도배 방지 및 신고 기능
-- 익명 로그인 사용자의 한마디 작성 간격·중복 문구와 신고 도배를 DB에서 제한합니다.
-- 신고자는 익명 로그인 세션(계정) 기준으로 한마디당 1회 신고할 수 있습니다.
-- 여러 번 실행해도 안전하도록 작성했습니다.

create or replace function public.place_comments_before_insert()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_uid uuid := auth.uid();
  v_request_role text := auth.jwt() ->> 'role';
begin
  if coalesce(v_request_role, '') not in ('anon', 'authenticated') then
    return new;
  end if;
  if v_uid is null then
    raise exception '한마디를 남기려면 먼저 이용자 확인이 필요해요.';
  end if;

  new.user_id := v_uid;
  new.hidden := false;
  new.created_at := now();
  new.body := btrim(new.body);
  new.nickname := nullif(btrim(coalesce(new.nickname, '')), '');

  perform pg_advisory_xact_lock(hashtextextended(v_uid::text, 0));
  perform public.ppx_guard('comment');

  if exists (
    select 1 from public.place_comments c
    where c.user_id = v_uid
      and c.created_at > now() - interval '30 seconds'
  ) then
    raise exception '한마디는 30초에 한 번씩 남길 수 있어요. 잠시 기다려 주세요.';
  end if;

  if exists (
    select 1 from public.place_comments c
    where c.user_id = v_uid
      and c.place_id = new.place_id
      and lower(c.body) = lower(new.body)
      and c.created_at > now() - interval '1 day'
  ) then
    raise exception '같은 내용은 하루에 한 번만 남길 수 있어요.';
  end if;
  return new;
end;
$$;

create table if not exists public.place_comment_reports (
  id bigint generated by default as identity primary key,
  comment_id bigint not null references public.place_comments(id) on delete cascade,
  reporter uuid not null references public.profiles(id) on delete cascade,
  reason text not null check (reason in ('abuse', 'spam', 'privacy', 'other')),
  status text not null default 'pending' check (status in ('pending', 'resolved')),
  created_at timestamptz not null default now(),
  constraint place_comment_reports_comment_reporter_key unique (comment_id, reporter)
);

create index if not exists place_comment_reports_status_idx
  on public.place_comment_reports (status, created_at desc);
create index if not exists place_comment_reports_reporter_idx
  on public.place_comment_reports (reporter, created_at desc);

create or replace function public.place_comment_reports_before_insert()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_uid uuid := auth.uid();
begin
  if v_uid is null then
    raise exception '한마디 신고는 이용자 확인 후 할 수 있어요.';
  end if;

  new.reporter := v_uid;
  new.status := 'pending';
  new.created_at := now();

  if exists (
    select 1 from public.place_comments c
    where c.id = new.comment_id and c.user_id = v_uid
  ) then
    raise exception '내가 쓴 한마디는 신고할 수 없어요.';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended(v_uid::text || ':comment-report', 0)
  );

  if (
    select count(*) from public.place_comment_reports r
    where r.reporter = v_uid
      and r.created_at > now() - interval '1 day'
  ) >= 10 then
    raise exception '하루 신고는 10회까지 할 수 있어요.';
  end if;
  return new;
end;
$$;

drop trigger if exists place_comment_reports_before_insert
  on public.place_comment_reports;
create trigger place_comment_reports_before_insert
  before insert on public.place_comment_reports
  for each row execute function public.place_comment_reports_before_insert();

alter table public.place_comment_reports enable row level security;

drop policy if exists "comment reports: 운영자 조회"
  on public.place_comment_reports;
create policy "comment reports: 운영자 조회"
  on public.place_comment_reports
  for select to authenticated
  using ((select public.is_admin()));

drop policy if exists "comment reports: 신고 추가"
  on public.place_comment_reports;
-- 신고자·본인 댓글 여부·하루 제한은 보안 트리거가 검증합니다.
create policy "comment reports: 신고 추가"
  on public.place_comment_reports
  for insert to authenticated
  with check (true);

drop policy if exists "comment reports: 운영자 처리"
  on public.place_comment_reports;
create policy "comment reports: 운영자 처리"
  on public.place_comment_reports
  for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

revoke all on public.place_comment_reports from anon, authenticated;
grant select on public.place_comment_reports to authenticated;
grant insert (comment_id, reason) on public.place_comment_reports to authenticated;
grant update (status) on public.place_comment_reports to authenticated;

revoke all on function public.place_comments_before_insert()
  from public, anon, authenticated;
revoke all on function public.place_comment_reports_before_insert()
  from public, anon, authenticated;
