-- 2026-11-09 한마디 도배 방지와 신고 기능 추가
-- 같은 기기에서 빠른 연속 작성·동일 문구 반복을 막고, 이용자 신고는 운영자만 확인할 수 있게 합니다.
-- 여러 번 실행해도 안전합니다.

create or replace function public.place_comments_before_insert()
returns trigger language plpgsql as $$
begin
  if current_user not in ('anon', 'authenticated') then return new; end if;
  new.user_id := auth.uid();
  new.hidden := false;
  new.created_at := now();
  new.body := btrim(new.body);
  new.nickname := nullif(btrim(coalesce(new.nickname, '')), '');
  perform public.ppx_guard('comment');
  perform pg_advisory_xact_lock(hashtextextended(auth.uid()::text, 0));
  if exists (select 1 from public.place_comments
             where user_id = auth.uid() and created_at > now() - interval '30 seconds') then
    raise exception '한마디는 30초에 한 번씩 남길 수 있어요. 잠시 기다려 주세요.';
  end if;
  if exists (select 1 from public.place_comments
             where user_id = auth.uid() and place_id = new.place_id
               and lower(body) = lower(new.body) and created_at > now() - interval '1 day') then
    raise exception '같은 내용은 하루에 한 번만 남길 수 있어요.';
  end if;
  return new;
end $$;

create table if not exists public.place_comment_reports (
  id bigint generated by default as identity primary key,
  comment_id bigint not null references public.place_comments(id) on delete cascade,
  reporter uuid not null references public.profiles(id) on delete cascade,
  reason text not null check (reason in ('abuse','spam','privacy','other')),
  status text not null default 'pending' check (status in ('pending','resolved')),
  created_at timestamptz not null default now(),
  unique (comment_id, reporter)
);
create index if not exists place_comment_reports_status_idx
  on public.place_comment_reports (status, created_at desc);
create index if not exists place_comment_reports_reporter_idx
  on public.place_comment_reports (reporter, created_at desc);

create or replace function public.place_comment_reports_before_insert()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then raise exception '한마디 신고는 이용자 확인 후 할 수 있어요'; end if;
  new.reporter := auth.uid();
  new.status := 'pending';
  new.created_at := now();
  if exists (select 1 from public.place_comments where id = new.comment_id and user_id = auth.uid()) then
    raise exception '내가 쓴 한마디는 신고할 수 없어요';
  end if;
  perform pg_advisory_xact_lock(hashtextextended(auth.uid()::text || ':comment-report', 0));
  if (select count(*) from public.place_comment_reports
      where reporter = auth.uid() and created_at > now() - interval '1 day') >= 10 then
    raise exception '하루 신고는 10회까지 할 수 있어요.';
  end if;
  return new;
end $$;
drop trigger if exists place_comment_reports_before_insert on public.place_comment_reports;
create trigger place_comment_reports_before_insert before insert on public.place_comment_reports
  for each row execute function public.place_comment_reports_before_insert();

alter table public.place_comment_reports enable row level security;
drop policy if exists "comment reports: 운영자 조회" on public.place_comment_reports;
create policy "comment reports: 운영자 조회" on public.place_comment_reports
  for select using (public.is_admin());
drop policy if exists "comment reports: 신고 추가" on public.place_comment_reports;
create policy "comment reports: 신고 추가" on public.place_comment_reports
  for insert to authenticated
  with check (
    reporter = auth.uid()
    and exists (select 1 from public.place_comments c where c.id = comment_id and c.user_id is distinct from auth.uid())
  );
drop policy if exists "comment reports: 운영자 처리" on public.place_comment_reports;
create policy "comment reports: 운영자 처리" on public.place_comment_reports
  for update using (public.is_admin()) with check (public.is_admin());
revoke all on public.place_comment_reports from anon, authenticated;
grant select, update (status) on public.place_comment_reports to authenticated;
grant insert (comment_id, reason) on public.place_comment_reports to authenticated;
