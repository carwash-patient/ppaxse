-- 4) 도배 방지: 막힌 사람 · 하루 개수 제한 (가입 없이 쓰는 사람도 기기마다 따로 셈)
create or replace function public.ppx_guard(what text)
returns void language plpgsql stable security definer set search_path = public as $$
declare n int; lim int;
begin
  if exists (select 1 from public.profiles where id = auth.uid() and blocked) then
    raise exception '이 기기에서는 지금 보낼 수 없어요. 문제가 있다면 운영자에게 알려주세요.';
  end if;
  if what = 'report' then
    lim := 30; select count(*) into n from public.place_reports where reporter = auth.uid() and created_at > now() - interval '1 day';
  elsif what = 'place' then
    lim := 10; select count(*) into n from public.places where submitted_by = auth.uid() and created_at > now() - interval '1 day';
  else
    lim := 100; select count(*) into n from public.place_checks where user_id = auth.uid() and created_at > now() - interval '1 day';
  end if;
  if n >= lim then
    raise exception '오늘은 더 보낼 수 없어요. 내일 다시 부탁드려요.';
  end if;
end $$;

-- 5) '정보가 맞아요' 기록 (한 사람이 한 세차장에 하루 한 번)
create table if not exists public.place_checks (
  id          bigint generated by default as identity primary key,
  place_id    bigint not null references public.places(id) on delete cascade,
  user_id     uuid references public.profiles(id) on delete set null,
  created_on  date not null default current_date,
  created_at  timestamptz not null default now()
);
create unique index if not exists place_checks_once_idx on public.place_checks (place_id, user_id, created_on);
create index if not exists place_checks_user_idx on public.place_checks (user_id, created_at);

create or replace function public.place_checks_before_insert()
returns trigger language plpgsql as $$
begin
  if current_user not in ('anon', 'authenticated') then return new; end if;
  new.user_id := auth.uid();
  new.created_on := current_date;
  new.created_at := now();
  perform public.ppx_guard('check');
  return new;
end $$;
drop trigger if exists place_checks_before_insert on public.place_checks;
create trigger place_checks_before_insert before insert on public.place_checks
  for each row execute function public.place_checks_before_insert();

-- 확인하면 세차장의 '최근 확인'과 횟수를 올림 (일반 사용자는 places를 못 고치므로 security definer)
create or replace function public.place_checks_after_insert()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  update public.places set checked_at = new.created_at, check_count = check_count + 1 where id = new.place_id;
  return new;
end $$;
drop trigger if exists place_checks_after_insert on public.place_checks;
create trigger place_checks_after_insert after insert on public.place_checks
  for each row execute function public.place_checks_after_insert();

alter table public.place_checks enable row level security;
drop policy if exists "checks: 조회" on public.place_checks;
create policy "checks: 조회" on public.place_checks
  for select using (user_id = auth.uid() or public.is_admin());
drop policy if exists "checks: 확인" on public.place_checks;
create policy "checks: 확인" on public.place_checks
  for insert to authenticated
  with check (exists (select 1 from public.places p where p.id = place_id and p.status = 'approved'));

-- 6) 추가 요청·제보에도 막기·하루 제한 적용
