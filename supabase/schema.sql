on conflict (id) do update set public = false, file_size_limit = 3145728,
  allowed_mime_types = array['image/jpeg','image/png','image/webp'];

drop policy if exists "report-photos: 올리기" on storage.objects;
create policy "report-photos: 올리기" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'report-photos' and (storage.foldername(name))[1] = auth.uid()::text
              and not exists (select 1 from public.profiles where id = auth.uid() and blocked));
drop policy if exists "report-photos: 보기" on storage.objects;
create policy "report-photos: 보기" on storage.objects
  for select to authenticated
  using (bucket_id = 'report-photos' and ((storage.foldername(name))[1] = auth.uid()::text or public.is_admin()));
drop policy if exists "report-photos: 지우기" on storage.objects;
create policy "report-photos: 지우기" on storage.objects
  for delete to authenticated
  using (bucket_id = 'report-photos' and public.is_admin());

