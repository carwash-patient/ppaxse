-- ── 1. 회원 정보 ───────────────────────────────────────────────
create table if not exists public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  nickname    text check (char_length(nickname) between 1 and 20),
  skill       text check (skill in ('beginner','mid','pro','maniac')),
  cars        text[] not null default '{}',
  role        text not null default 'user' check (role in ('user','admin','owner')),
  created_at  timestamptz not null default now()
);

alter table public.profiles add column if not exists cars text[] not null default '{}';
-- 기본 지역 (예: {"region":"인천 남동구"}). 위치를 못 받을 때 지도를 여기서 시작
alter table public.profiles add column if not exists home jsonb
  check (home is null or (jsonb_typeof(home) = 'object' and octet_length(home::text) <= 200));

-- 가입하면 profiles 행을 자동으로 만듦 (기본 역할: user). 가입 화면에서 넘긴 닉네임·숙련도·차종 저장

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, nickname, skill, cars)
  values (
    new.id,
    left(coalesce(nullif(trim(new.raw_user_meta_data->>'nickname'), ''), split_part(new.email, '@', 1)), 20),
    case when new.raw_user_meta_data->>'skill' in ('beginner','mid','pro','maniac')
         then new.raw_user_meta_data->>'skill' end,
    coalesce(array(select jsonb_array_elements_text(new.raw_user_meta_data->'cars')), '{}')
  )
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- 지금 로그인한 사람이 운영자인가? (권한 규칙에서 사용)
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

-- ── 2. 세차장 ─────────────────────────────────────────────────
create table if not exists public.places (
  id            bigint generated by default as identity primary key,
  name          text not null check (char_length(name) between 1 and 60),
  addr          text not null default '' check (char_length(addr) <= 200),
  region        text not null default '',          -- 예: '인천 남동구'
  type          text not null default 'wash'
                check (type in ('self','hand','detail','notouch','auto','wash','etc')),   -- 대표 종류 (지도 아이콘)
  types         text[] not null default '{}',   -- 함께 있는 종류 전부 (예: {self,notouch}). 비면 type 하나
  lat           double precision not null check (lat between 33 and 39),
  lng           double precision not null check (lng between 124 and 132),
  tel           text check (char_length(tel) <= 30),
  hours         text check (char_length(hours) <= 60),
  price         text check (char_length(price) <= 200),
  memo          text check (char_length(memo) <= 500),  -- 요청할 때 남기는 설명
  -- 시설 정보: null = 아직 모름(정보 준비중), true/false = 확인됨
  h24 boolean, foam boolean, under boolean, indoor boolean, myitem boolean, reserve boolean,

  status        text not null default 'pending'
                check (status in ('pending','approved','rejected','closed','unlocated')),
  source        text not null default 'user'
                check (source in ('public_data','user','owner','admin')),
  source_ref    text unique,                         -- 공공데이터 관리번호 (중복 방지)
  submitted_by  uuid references public.profiles(id) on delete set null,
  reviewed_by   uuid references public.profiles(id) on delete set null,
  reviewed_at   timestamptz,
  reject_reason text check (char_length(reject_reason) <= 200),
  owner_id      uuid references public.profiles(id) on delete set null,  -- 출시 후: 인증된 사장님
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- 함께 있는 종류 (예전에 만든 표에도 추가)
alter table public.places add column if not exists types text[] not null default '{}';
alter table public.places drop constraint if exists places_types_check;
alter table public.places add constraint places_types_check
  check (types <@ array['self','hand','detail','notouch','auto','wash','etc']::text[] and cardinality(types) <= 7);

-- 대표 종류는 항상 '함께 있는 종류' 맨 앞에 들어가도록 정리 (중복 제거)
create or replace function public.places_fix_types()
returns trigger language plpgsql as $$
begin
  new.types := array(
    select t from unnest(array[new.type] || coalesce(new.types, '{}')) with ordinality as x(t, i)
    group by t order by min(i));
  return new;
end $$;

drop trigger if exists places_fix_types on public.places;
create trigger places_fix_types
  before insert or update of type, types on public.places
  for each row execute function public.places_fix_types();

create index if not exists places_types_idx on public.places using gin (types);

-- 예전에 만든 표에도 'unlocated' 상태를 허용
alter table public.places drop constraint if exists places_status_check;
alter table public.places add constraint places_status_check
  check (status in ('pending','approved','rejected','closed','unlocated'));

create index if not exists places_status_idx    on public.places (status);
create index if not exists places_latlng_idx    on public.places (lat, lng);
create index if not exists places_submitted_idx on public.places (submitted_by);

-- 수정 시각 자동 기록 + 승인/거절한 운영자 자동 기록
create or replace function public.places_before_update()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  if new.status is distinct from old.status and new.status in ('approved','rejected') then
    new.reviewed_by := auth.uid();
    new.reviewed_at := now();
  end if;
  return new;
end $$;

drop trigger if exists places_before_update on public.places;
create trigger places_before_update
  before update on public.places
  for each row execute function public.places_before_update();

-- 내가 아직 확인받지 못한 요청 수 (도배 방지용, 권한과 무관하게 정확히 세기 위해 security definer)
create or replace function public.my_pending_count()
returns int language sql stable security definer set search_path = public as $$
  select count(*)::int from public.places where submitted_by = auth.uid() and status = 'pending';
$$;

-- 앱(anon/authenticated)으로 들어온 일반 사용자의 요청은 항상 '대기' 상태, 요청자는 본인으로 고정.
-- SQL Editor·관리 도구(postgres 등)로 넣는 공공데이터, 운영자의 직접 등록은 그대로 둠.
create or replace function public.places_before_insert()
returns trigger language plpgsql as $$
begin
  if current_user not in ('anon', 'authenticated') or public.is_admin() then
    return new;
  end if;
  new.status        := 'pending';
  new.source        := 'user';
  new.submitted_by  := auth.uid();
  new.source_ref    := null;
  new.owner_id      := null;
  new.reviewed_by   := null;
  new.reviewed_at   := null;
  new.reject_reason := null;
  if public.my_pending_count() >= 5 then
    raise exception '확인을 기다리는 요청이 5개 있어요. 처리된 뒤에 다시 요청해 주세요.';
  end if;
  return new;
end $$;

drop trigger if exists places_before_insert on public.places;
create trigger places_before_insert
  before insert on public.places
  for each row execute function public.places_before_insert();

