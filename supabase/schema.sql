--  역할(role)
--    user  : 일반 사용자 — 세차장 추가 요청, (나중에) 리뷰·제보
--    admin : 운영자     — 요청 승인/거절, 모든 정보 수정
--    owner : 세차장 사장님 — 출시 후 사용 (내 매장 정보 관리). 지금은 자리만 마련
--
--  세차장 상태(status)
--    pending  : 추가 요청됨, 운영자 확인 대기 (지도에 안 보임)
--    approved : 승인됨 → 지도에 표시
--    rejected : 거절됨 (요청한 본인만 사유와 함께 볼 수 있음)
--    closed   : 폐업 등으로 숨김
