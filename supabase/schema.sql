-- 7) 운영자: 제보 막기/풀기
create or replace function public.admin_block(uid uuid, on_off boolean)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception '운영자만 할 수 있어요'; end if;
  update public.profiles set blocked = on_off where id = uid and role <> 'admin';
end $$;
revoke execute on function public.admin_block(uuid, boolean) from anon;

-- 8) 가입 없이 쓰던 기기 → 가입/로그인하면 그동안의 요청·제보·확인을 계정으로 옮김
--    (가입 없이 쓰는 동안 받은 1회용 번호를 가진 기기만 옮길 수 있음)
create table if not exists public.anon_claims (
  token      uuid primary key default gen_random_uuid(),
  anon_id    uuid not null,
  created_at timestamptz not null default now()
);
alter table public.anon_claims enable row level security;   -- 정책 없음 = 앱에서 직접 못 봄

create or replace function public.start_claim()
returns uuid language plpgsql security definer set search_path = public as $$
declare t uuid;
begin
  if auth.uid() is null or coalesce((auth.jwt()->>'is_anonymous')::boolean, false) is not true then
    return null;
  end if;
  delete from public.anon_claims where anon_id = auth.uid() or created_at < now() - interval '30 days';
  insert into public.anon_claims (anon_id) values (auth.uid()) returning token into t;
  return t;
end $$;

create or replace function public.finish_claim(t uuid)
returns int language plpgsql security definer set search_path = public as $$
declare a uuid; n int := 0; k int;
begin
  if auth.uid() is null or coalesce((auth.jwt()->>'is_anonymous')::boolean, false) then return 0; end if;
  delete from public.anon_claims where token = t returning anon_id into a;
  if a is null or a = auth.uid() then return 0; end if;
  update public.places set submitted_by = auth.uid() where submitted_by = a;        get diagnostics k = row_count; n := n + k;
  update public.place_reports set reporter = auth.uid() where reporter = a;         get diagnostics k = row_count; n := n + k;
  -- 같은 날 같은 세차장을 두 번 확인한 기록은 하나만 남김
  delete from public.place_checks c where c.user_id = a and exists (
    select 1 from public.place_checks d where d.user_id = auth.uid() and d.place_id = c.place_id and d.created_on = c.created_on);
  update public.place_checks set user_id = auth.uid() where user_id = a;            get diagnostics k = row_count; n := n + k;
  return n;
end $$;
revoke execute on function public.start_claim() from anon;
revoke execute on function public.finish_claim(uuid) from anon;

