-- ── 1. 회원 정보 ───────────────────────────────────────────────
create table if not exists public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  nickname    text check (char_length(nickname) between 1 and 20),
  skill       text check (skill in ('beginner','mid','pro','maniac')),
  cars        text[] not null default '{}',
  role        text not null default 'user' check (role in ('user','admin','owner')),
  created_at  timestamptz not null default now()
);

alter table public.profiles add column if not exists cars text[] not null default '{}';

-- 가입하면 profiles 행을 자동으로 만듦 (기본 역할: user). 가입 화면에서 넘긴 닉네임·숙련도·차종 저장

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, nickname, skill, cars)
  values (
    new.id,
    left(coalesce(nullif(trim(new.raw_user_meta_data->>'nickname'), ''), split_part(new.email, '@', 1)), 20),
    case when new.raw_user_meta_data->>'skill' in ('beginner','mid','pro','maniac')
         then new.raw_user_meta_data->>'skill' end,
    coalesce(array(select jsonb_array_elements_text(new.raw_user_meta_data->'cars')), '{}')
  )
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- 지금 로그인한 사람이 운영자인가? (권한 규칙에서 사용)
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

-- ── 2. 세차장 ─────────────────────────────────────────────────
create table if not exists public.places (
  id            bigint generated by default as identity primary key,
  name          text not null check (char_length(name) between 1 and 60),
  addr          text not null default '' check (char_length(addr) <= 200),
  region        text not null default '',          -- 예: '인천 남동구'
  type          text not null default 'wash'
                check (type in ('self','hand','detail','notouch','auto','wash','etc')),
  lat           double precision not null check (lat between 33 and 39),
  lng           double precision not null check (lng between 124 and 132),
  tel           text check (char_length(tel) <= 30),
  hours         text check (char_length(hours) <= 60),
  price         text check (char_length(price) <= 200),
  memo          text check (char_length(memo) <= 500),  -- 요청할 때 남기는 설명
  -- 시설 정보: null = 아직 모름(정보 준비중), true/false = 확인됨
  h24 boolean, foam boolean, under boolean, indoor boolean, myitem boolean, reserve boolean,

  status        text not null default 'pending'
                check (status in ('pending','approved','rejected','closed')),
  source        text not null default 'user'
                check (source in ('public_data','user','owner','admin')),
  source_ref    text unique,                         -- 공공데이터 관리번호 (중복 방지)
  submitted_by  uuid references public.profiles(id) on delete set null,
  reviewed_by   uuid references public.profiles(id) on delete set null,
  reviewed_at   timestamptz,
  reject_reason text check (char_length(reject_reason) <= 200),
  owner_id      uuid references public.profiles(id) on delete set null,  -- 출시 후: 인증된 사장님
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create index if not exists places_status_idx    on public.places (status);
create index if not exists places_latlng_idx    on public.places (lat, lng);
create index if not exists places_submitted_idx on public.places (submitted_by);

-- 수정 시각 자동 기록 + 승인/거절한 운영자 자동 기록
create or replace function public.places_before_update()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  if new.status is distinct from old.status and new.status in ('approved','rejected') then
    new.reviewed_by := auth.uid();
    new.reviewed_at := now();
  end if;
  return new;
end $$;

drop trigger if exists places_before_update on public.places;
create trigger places_before_update
  before update on public.places
  for each row execute function public.places_before_update();

-- 내가 아직 확인받지 못한 요청 수 (도배 방지용, 권한과 무관하게 정확히 세기 위해 security definer)
create or replace function public.my_pending_count()
returns int language sql stable security definer set search_path = public as $$
  select count(*)::int from public.places where submitted_by = auth.uid() and status = 'pending';
$$;

-- 앱(anon/authenticated)으로 들어온 일반 사용자의 요청은 항상 '대기' 상태, 요청자는 본인으로 고정.
-- SQL Editor·관리 도구(postgres 등)로 넣는 공공데이터, 운영자의 직접 등록은 그대로 둠.
create or replace function public.places_before_insert()
returns trigger language plpgsql as $$
begin
  if current_user not in ('anon', 'authenticated') or public.is_admin() then
    return new;
  end if;
  new.status        := 'pending';
  new.source        := 'user';
  new.submitted_by  := auth.uid();
  new.source_ref    := null;
  new.owner_id      := null;
  new.reviewed_by   := null;
  new.reviewed_at   := null;
  new.reject_reason := null;
  if public.my_pending_count() >= 5 then
    raise exception '확인을 기다리는 요청이 5개 있어요. 처리된 뒤에 다시 요청해 주세요.';
  end if;
  return new;
end $$;

drop trigger if exists places_before_insert on public.places;
create trigger places_before_insert
  before insert on public.places
  for each row execute function public.places_before_insert();

-- ── 3. 권한 규칙 (Row Level Security) ─────────────────────────
alter table public.profiles enable row level security;
alter table public.places   enable row level security;

-- 회원 정보: 본인 것만 보고 수정 / 운영자는 전체 조회
drop policy if exists "profiles: 본인 조회" on public.profiles;
create policy "profiles: 본인 조회" on public.profiles
  for select using (id = auth.uid() or public.is_admin());

drop policy if exists "profiles: 본인 수정" on public.profiles;
create policy "profiles: 본인 수정" on public.profiles
  for update using (id = auth.uid())
  with check (id = auth.uid());

-- 역할(role)은 본인이 바꿀 수 없음 → 열 단위로 수정 권한 제한
revoke update on public.profiles from anon, authenticated;
grant  update (nickname, skill, cars) on public.profiles to authenticated;

-- 세차장 조회: 승인된 곳은 누구나 / 내가 요청한 곳은 본인 / 운영자는 전부
drop policy if exists "places: 조회" on public.places;
create policy "places: 조회" on public.places
  for select using (
    status = 'approved'
    or submitted_by = auth.uid()
    or public.is_admin()
  );

-- 세차장 추가 요청: 로그인한 사용자 누구나 (내용은 위 트리거가 '대기'로 고정)
drop policy if exists "places: 추가 요청" on public.places;
create policy "places: 추가 요청" on public.places
  for insert to authenticated
  with check (true);

-- 승인·거절·수정·삭제: 운영자만
drop policy if exists "places: 운영자 수정" on public.places;
create policy "places: 운영자 수정" on public.places
  for update using (public.is_admin()) with check (public.is_admin());

drop policy if exists "places: 운영자 삭제" on public.places;
create policy "places: 운영자 삭제" on public.places
  for delete using (public.is_admin());

-- ── 4. 정보 제보 ("정보가 달라요") ───────────────────────────────
--  사용자가 이미 등록된 세차장의 종류·시설·폐업 여부를 고쳐달라고 알림.
--  운영자가 확인한 뒤 반영(applied)하거나 무시(dismissed). 반영은 운영자 화면에서 places를 직접 수정.
create table if not exists public.place_reports (
  id           bigint generated by default as identity primary key,
  place_id     bigint not null references public.places(id) on delete cascade,
  reporter     uuid references public.profiles(id) on delete set null,
  suggest      jsonb not null default '{}'::jsonb
               check (jsonb_typeof(suggest) = 'object' and octet_length(suggest::text) <= 2000),
  memo         text check (char_length(memo) <= 500),
  status       text not null default 'pending' check (status in ('pending','applied','dismissed')),
  reviewed_by  uuid references public.profiles(id) on delete set null,
  reviewed_at  timestamptz,
  created_at   timestamptz not null default now()
);

create index if not exists place_reports_status_idx   on public.place_reports (status);
create index if not exists place_reports_reporter_idx on public.place_reports (reporter);

-- 내가 아직 처리받지 못한 제보 수 (도배 방지)
create or replace function public.my_pending_reports()
returns int language sql stable security definer set search_path = public as $$
  select count(*)::int from public.place_reports where reporter = auth.uid() and status = 'pending';
$$;

-- 앱으로 들어온 제보는 요청자=본인, 상태=대기로 고정. 대기 제보 10개 제한
create or replace function public.place_reports_before_insert()
returns trigger language plpgsql as $$
begin
  if current_user not in ('anon', 'authenticated') then
    return new;
  end if;
  new.reporter    := auth.uid();
  new.status      := 'pending';
  new.reviewed_by := null;
  new.reviewed_at := null;
  if public.my_pending_reports() >= 10 then
    raise exception '확인을 기다리는 제보가 10개 있어요. 처리된 뒤에 다시 보내 주세요.';
  end if;
  return new;
end $$;

drop trigger if exists place_reports_before_insert on public.place_reports;
create trigger place_reports_before_insert
  before insert on public.place_reports
  for each row execute function public.place_reports_before_insert();

-- 처리한 운영자·시각 자동 기록
create or replace function public.place_reports_before_update()
returns trigger language plpgsql as $$
begin
  if new.status is distinct from old.status and new.status in ('applied','dismissed') then
    new.reviewed_by := auth.uid();
    new.reviewed_at := now();
  end if;
  return new;
end $$;

drop trigger if exists place_reports_before_update on public.place_reports;
create trigger place_reports_before_update
  before update on public.place_reports
  for each row execute function public.place_reports_before_update();

alter table public.place_reports enable row level security;

-- 조회: 내가 보낸 제보 / 운영자는 전부
drop policy if exists "reports: 조회" on public.place_reports;
create policy "reports: 조회" on public.place_reports
  for select using (reporter = auth.uid() or public.is_admin());

-- 제보: 로그인한 사용자 누구나, 지도에 보이는(승인된) 세차장에만
drop policy if exists "reports: 제보" on public.place_reports;
create policy "reports: 제보" on public.place_reports
  for insert to authenticated
  with check (exists (select 1 from public.places p where p.id = place_id and p.status = 'approved'));

-- 처리·삭제: 운영자만
drop policy if exists "reports: 운영자 처리" on public.place_reports;
create policy "reports: 운영자 처리" on public.place_reports
  for update using (public.is_admin()) with check (public.is_admin());

drop policy if exists "reports: 운영자 삭제" on public.place_reports;
create policy "reports: 운영자 삭제" on public.place_reports
  for delete using (public.is_admin());

