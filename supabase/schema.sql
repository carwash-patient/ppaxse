--
--  1) 정보 제보: 15초에 한 번, 같은 세차장은 10분에 한 번
--  2) 세차장 추가 요청: 30초에 한 번
--  3) 막힌 사람은 한마디 신고도 못 함
--  4) 이상 요청 기록(ppx_abuse_log): 제한에 걸린 요청을 운영자가 볼 수 있게 남김
