-- 운영자: 채널별 새 방문자 → 응모 → 가입 (최근 days일)
create or replace function public.admin_channel_stats(days int default 30)
returns json language plpgsql stable security definer set search_path = public as $$
declare since timestamptz := now() - make_interval(days => greatest(1, least(coalesce(days, 30), 365)));
        since_day date := (since at time zone 'Asia/Seoul')::date;
begin
  if not public.is_admin() then raise exception '운영자만 할 수 있어요'; end if;
  return json_build_object(
    'by_ref', coalesce((select json_agg(t order by t.visitors desc, t.ref) from (
      select u.ref, sum(u.visitors)::int as visitors, sum(u.entries)::int as entries, sum(u.members)::int as members
      from (
        -- 꼬리표 달고 처음 들어온 기기
        select r.ref, count(*) as visitors, 0 as entries, 0 as members
        from public.ppx_visitor_ref r where r.first_at >= since group by r.ref
        union all
        -- 꼬리표 없이 처음 들어온 기기 (이 기간에 처음 방문)
        select '(꼬리표 없음)', count(*), 0, 0 from (
          select v.visitor from public.ppx_visits v group by v.visitor
          having min(v.day) >= since_day) f
        where not exists (select 1 from public.ppx_visitor_ref r where r.visitor = f.visitor)
        union all
        -- 응모한 사람 (기기·계정 기준)
        select coalesce(p.signup_ref, '(꼬리표 없음)'), 0, count(distinct e.user_id), 0
        from public.event_entries e join public.profiles p on p.id = e.user_id
        where e.created_at >= since group by 1
        union all
        -- 가입한 회원
        select coalesce(p.signup_ref, '(꼬리표 없음)'), 0, 0, count(*)
        from public.profiles p where p.created_at >= since and public.ppx_is_member(p.id) group by 1
      ) u
      group by u.ref
      having sum(u.visitors) + sum(u.entries) + sum(u.members) > 0) t), '[]'::json),
    'by_source', coalesce((select json_agg(json_build_object('source', s.src, 'members', s.n, 'notes', s.notes) order by s.n desc) from (
      select coalesce(p.signup_source, '(답 안 함)') as src, count(*) as n,
             array_remove(array_agg(distinct p.signup_note), null) as notes
      from public.profiles p where p.created_at >= since and public.ppx_is_member(p.id)
      group by 1) s), '[]'::json)
  );
end $$;
revoke all on function public.admin_channel_stats(int) from public, anon;
grant execute on function public.admin_channel_stats(int) to authenticated;


-- ── 17. 대표 세차장 종류 투표 (2026-11-10d) ──
-- 2026-11-10d 대표 세차장 종류 투표
--
--  · 후기 페이지에서 방문자가 고른 '대표 종류'(1개)와 '같이 있는 종류'(여러 개)를 1인 1표로 저장
--  · 같은 사람이 같은 세차장에 30일 안에 다시 고르면 새 표가 아니라 고친 것으로 처리
--  · 표는 화면에서 직접 읽거나 쓸 수 없음: 저장은 ppx_vote_type, 보기는 운영자만 admin_type_votes
--  · 가입하면 가입 전 기기에서 남긴 표도 계정으로 옮김 (finish_claim)
--  · 기프티콘 응모 조건에 '어떤 세차장인지 고르기'도 포함 (시기·시설 대신 종류만 골라도 응모됨)
--  · 여러 번 실행해도 안전함

create table if not exists public.place_type_votes (
  id         bigint generated by default as identity primary key,
  place_id   bigint not null references public.places(id) on delete cascade,
  user_id    uuid not null,
  main       text not null check (main in ('self','hand','notouch','auto','detail')),
  extras     text[] not null default '{}'
             check (extras <@ array['self','hand','notouch','auto','detail']::text[] and cardinality(extras) <= 4),
  created_at timestamptz not null default now()
);
create index if not exists place_type_votes_place_idx on public.place_type_votes (place_id);
create index if not exists place_type_votes_user_idx on public.place_type_votes (user_id, place_id, created_at desc);
alter table public.place_type_votes enable row level security;
revoke all on public.place_type_votes from public, anon, authenticated;

-- 표 남기기 (후기 페이지)
create or replace function public.ppx_vote_type(pid bigint, m text, ex text[] default '{}')
returns void language plpgsql security definer set search_path = public as $$
declare v uuid := auth.uid(); e text[];
begin
  if v is null then raise exception '이용자 확인이 필요해요.'; end if;
  if m is null or m not in ('self','hand','notouch','auto','detail') then
    raise exception '어떤 세차장인지 하나 골라 주세요.';
  end if;
  if not exists (select 1 from public.places where id = pid and status = 'approved') then
    raise exception '세차장을 찾을 수 없어요.';
  end if;
  perform public.ppx_guard('check');
  e := array(select distinct x from unnest(coalesce(ex, '{}'::text[])) x
             where x in ('self','hand','notouch','auto','detail') and x <> m order by x);
  perform pg_advisory_xact_lock(hashtextextended(v::text || ':typevote:' || pid, 0));
  update public.place_type_votes set main = m, extras = e, created_at = now()
   where user_id = v and place_id = pid and created_at > now() - interval '30 days';
  if not found then
    insert into public.place_type_votes (place_id, user_id, main, extras) values (pid, v, m, e);
  end if;
end $$;
revoke all on function public.ppx_vote_type(bigint, text, text[]) from public, anon;
grant execute on function public.ppx_vote_type(bigint, text, text[]) to authenticated;

