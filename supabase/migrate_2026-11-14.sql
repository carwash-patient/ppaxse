-- 2026-11-14 한마디 기프티콘 추첨: 하루 1번, 한 주 최대 3번 응모
-- migrate_2026-11-13.sql 다음에 실행. 여러 번 실행해도 안전합니다.
-- 운영자가 Supabase SQL Editor에서 '전체'를 한 번에 Run 합니다.
--
-- 무엇을 바꾸나
--  · 예전: 한 사람(기기·계정)당 한 주에 1번 응모
--  · 이제: 하루에 1번씩, 한 주에 최대 3번까지 응모 (응모권 3장)
--      - 같은 세차장으로는 한 주에 1번만 인정 (같은 곳을 매일 쓰는 것 방지)
--      - 응모번호는 지금처럼 한 주에 1개. 응모할 때마다 그 번호의 응모권이 1장씩 늘어남
--  · 추첨: 응모권이 많을수록 당첨 확률이 높음 (응모권 수만큼 가중치)
--      - 회원 추첨 2명 먼저 → 남은 사람 중 누구나 추첨 2명. 한 사람이 두 번 당첨되지는 않음 (그대로)
--  · 운영자가 한마디를 숨기면 그 한마디로 받은 응모권 1장만 빠짐. 응모권이 하나도 안 남으면 추첨에서 제외
--  · 가입·로그인하면 기기로 받은 응모권도 계정으로 합침 (같은 날·같은 세차장은 1장, 합쳐서 최대 3장)
--
-- 새 표: event_tickets (응모권). 쓰기는 함수로만, 읽기는 운영자만
-- 함수 권한은 2026-11-12 보안 수정과 같게 맞춤

begin;

-- ── 응모권 ──
create table if not exists public.event_tickets (
  id          bigint generated by default as identity primary key,
  entry_id    bigint not null references public.event_entries(id) on delete cascade,
  day         date not null,                       -- 응모한 날 (한국 시간)
  comment_id  bigint references public.place_comments(id) on delete set null,
  place_id    bigint,
  created_at  timestamptz not null default now(),
  unique (entry_id, day),
  unique (entry_id, place_id)
);
create index if not exists event_tickets_entry_idx on public.event_tickets (entry_id);

alter table public.event_tickets enable row level security;
drop policy if exists "tickets: 운영자 조회" on public.event_tickets;
create policy "tickets: 운영자 조회" on public.event_tickets
  for select to authenticated using ((select public.is_admin()));
revoke all on public.event_tickets from public, anon, authenticated;
grant select on public.event_tickets to authenticated;

-- 이미 있는 응모는 응모권 1장으로 옮김
insert into public.event_tickets (entry_id, day, comment_id, place_id, created_at)
select e.id, (e.created_at at time zone 'Asia/Seoul')::date, e.comment_id, c.place_id, e.created_at
from public.event_entries e
left join public.place_comments c on c.id = e.comment_id
where not exists (select 1 from public.event_tickets t where t.entry_id = e.id)
on conflict do nothing;

-- 한 주 최대 응모 횟수
create or replace function public.ppx_event_max_tickets()
returns int language sql immutable set search_path = pg_catalog, public, pg_temp as $$ select 3 $$;
revoke all on function public.ppx_event_max_tickets() from public, anon, authenticated;

-- 추첨에 들어가는 응모권 수 (숨긴 한마디의 응모권은 빼고, 막힌 사람·운영자는 0)
create or replace function public.ppx_entry_weight(e public.event_entries)
returns int language sql stable security definer set search_path = pg_catalog, public, pg_temp as $$
  select case when exists (select 1 from public.profiles p where p.id = e.user_id and (p.blocked or p.role = 'admin')) then 0
         else (select count(*)::int from public.event_tickets t
               join public.place_comments c on c.id = t.comment_id
               where t.entry_id = e.id and not c.hidden) end
$$;
revoke all on function public.ppx_entry_weight(public.event_entries) from public, anon, authenticated;

-- 추첨에 들어가는 응모인지 (남은 응모권이 1장 이상)
create or replace function public.ppx_entry_valid(e public.event_entries)
returns boolean language sql stable security definer set search_path = pg_catalog, public, pg_temp as $$
  select public.ppx_entry_weight(e) > 0
$$;
revoke all on function public.ppx_entry_valid(public.event_entries) from public, anon, authenticated;

-- ── 응모하기: 한마디를 저장한 직후 화면이 부름 ──
-- 돌려주는 값: { code, week, already, reason, tickets, max }
--   already=true면 이번 한마디로는 응모권이 늘지 않음. reason: 'today'(오늘 이미) / 'max'(이번 주 다 씀) / 'place'(이번 주 같은 세차장)
create or replace function public.ppx_enter_event(cid bigint)
returns json language plpgsql security definer set search_path = pg_catalog, public, pg_temp as $$
declare
  v uuid := auth.uid();
  w date := public.ppx_event_week(now());
  today date := (now() at time zone 'Asia/Seoul')::date;
  mx int := public.ppx_event_max_tickets();
  c public.place_comments;
  e public.event_entries;
  n int := 0;
  chars text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  k text; i int;
begin
  if v is null then raise exception '이용자 확인이 필요해요.'; end if;
  if today < public.ppx_event_start() then
    raise exception '기프티콘 추첨은 11월 14일(토)부터 응모할 수 있어요.';
  end if;
  if exists (select 1 from public.profiles where id = v and (blocked or role = 'admin')) then
    raise exception '이 계정은 추첨에 응모할 수 없어요.';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(v::text || ':event', 0));

  select * into c from public.place_comments where id = cid and user_id = v and not hidden;
  if not found then raise exception '응모할 한마디를 찾지 못했어요.'; end if;

  -- 이번 주 응모가 있으면: 오늘 이미 / 이번 주 다 씀 / 같은 세차장이면 번호만 돌려줌
  select * into e from public.event_entries where week = w and user_id = v;
  if found then
    select count(*) into n from public.event_tickets where entry_id = e.id;
    if n >= mx then
      return json_build_object('code', e.code, 'week', w, 'already', true, 'reason', 'max', 'tickets', n, 'max', mx);
    end if;
    if exists (select 1 from public.event_tickets where entry_id = e.id and day = today) then
      return json_build_object('code', e.code, 'week', w, 'already', true, 'reason', 'today', 'tickets', n, 'max', mx);
    end if;
    if exists (select 1 from public.event_tickets where entry_id = e.id and place_id = c.place_id) then
      return json_build_object('code', e.code, 'week', w, 'already', true, 'reason', 'place', 'tickets', n, 'max', mx);
    end if;
  end if;

  -- 응모 조건 (그대로)
  if c.created_at < now() - interval '2 hours' or public.ppx_event_week(c.created_at) <> w then
    raise exception '이번 주에 남긴 한마디로만 응모할 수 있어요.';
  end if;
  if char_length(c.body) < 10 then
    raise exception '응모하려면 한마디를 10자 이상 써 주세요.';
  end if;
  if not exists (select 1 from public.place_reports r
                 where r.reporter = v and r.place_id = c.place_id and r.created_at > c.created_at - interval '2 hours')
     and not exists (select 1 from public.place_checks k2
                 where k2.user_id = v and k2.place_id = c.place_id and k2.created_at > c.created_at - interval '2 hours')
     and not exists (select 1 from public.place_type_votes tv
                 where tv.user_id = v and tv.place_id = c.place_id and tv.created_at > c.created_at - interval '2 hours') then
    raise exception '응모하려면 다녀온 시기나 세차장 정보를 하나 이상 함께 알려 주세요.';
  end if;

  -- 이번 주 첫 응모면 응모번호를 새로 만듦
  if e.id is null then
    for i in 1..20 loop
      k := '';
      for j in 1..6 loop k := k || substr(chars, 1 + floor(random() * 32)::int, 1); end loop;
      k := substr(k, 1, 3) || '-' || substr(k, 4, 3);
      exit when not exists (select 1 from public.event_entries where code = k);
    end loop;
    insert into public.event_entries (week, user_id, comment_id, code) values (w, v, c.id, k) returning * into e;
  end if;

  insert into public.event_tickets (entry_id, day, comment_id, place_id) values (e.id, today, c.id, c.place_id);
  select count(*) into n from public.event_tickets where entry_id = e.id;
  return json_build_object('code', e.code, 'week', w, 'already', false, 'tickets', n, 'max', mx);
end $$;
revoke all on function public.ppx_enter_event(bigint) from public, anon, authenticated;
grant execute on function public.ppx_enter_event(bigint) to authenticated;

-- ── 누구나 볼 수 있는 현황 (+ 내 응모권 수, 오늘 응모했는지) ──
create or replace function public.ppx_event_status()
returns json language plpgsql stable security definer set search_path = pg_catalog, public, pg_temp as $$
declare
  v uuid := auth.uid();
  w date := greatest(public.ppx_event_week(now()), public.ppx_event_start());
  today date := (now() at time zone 'Asia/Seoul')::date;
  lw date;
begin
  select max(week) into lw from public.event_winners;
  return json_build_object(
    'start', public.ppx_event_start(),
    'week', w, 'week_end', w + 6, 'draw_date', w + 9,
    'max_tickets', public.ppx_event_max_tickets(),
    'all_count',    (select count(*) from public.event_entries e where e.week = w and public.ppx_entry_valid(e)),
    'member_count', (select count(*) from public.event_entries e where e.week = w and public.ppx_entry_valid(e) and public.ppx_is_member(e.user_id)),
    'winners_all', 2, 'winners_member', 2,
    'last', case when lw is null then null else json_build_object(
      'week', lw,
      'all_count',    (select count(*) from public.event_entries e where e.week = lw and public.ppx_entry_valid(e)),
      'member_count', (select count(*) from public.event_entries e where e.week = lw and public.ppx_entry_valid(e) and public.ppx_is_member(e.user_id)),
      'winners', (select json_agg(json_build_object('code', e.code, 'pool', x.pool) order by x.pool desc, e.code)
                  from public.event_winners x join public.event_entries e on e.id = x.entry_id where x.week = lw)
    ) end,
    'mine', case when v is null then '[]'::json else coalesce((
      select json_agg(json_build_object('week', e.week, 'code', e.code,
                      'won', (select x.pool from public.event_winners x where x.entry_id = e.id),
                      'valid', public.ppx_entry_valid(e),
                      'tickets', (select count(*) from public.event_tickets t where t.entry_id = e.id),
                      'valid_tickets', public.ppx_entry_weight(e),
                      'today', exists (select 1 from public.event_tickets t where t.entry_id = e.id and t.day = today))
                      order by e.week desc)
      from (select * from public.event_entries where user_id = v order by week desc limit 6) e), '[]'::json) end,
    'member', case when v is null then false else public.ppx_is_member(v) end
  );
end $$;
revoke all on function public.ppx_event_status() from public, anon, authenticated;
grant execute on function public.ppx_event_status() to anon, authenticated;

-- ── 실제 추첨: 응모권 수만큼 가중치 (가중 무작위 추출) ──
create or replace function public.ppx_event_draw_run(w date)
returns json language plpgsql security definer set search_path = pg_catalog, public, pg_temp as $$
begin
  perform pg_advisory_xact_lock(hashtextextended('event-draw:' || w::text, 0));
  if not exists (select 1 from public.event_winners where week = w) then
    insert into public.event_winners (week, entry_id, pool)
      select w, e.id, 'member' from public.event_entries e
      where e.week = w and public.ppx_entry_valid(e) and public.ppx_is_member(e.user_id)
      order by power(random(), 1.0 / public.ppx_entry_weight(e)) desc limit 2;
    insert into public.event_winners (week, entry_id, pool)
      select w, e.id, 'all' from public.event_entries e
      where e.week = w and public.ppx_entry_valid(e)
        and not exists (select 1 from public.event_winners x where x.week = w and x.entry_id = e.id)
      order by power(random(), 1.0 / public.ppx_entry_weight(e)) desc limit 2;
  end if;
  return (select coalesce(json_agg(json_build_object('code', e.code, 'pool', x.pool) order by x.pool desc), '[]'::json)
          from public.event_winners x join public.event_entries e on e.id = x.entry_id where x.week = w);
end $$;
revoke all on function public.ppx_event_draw_run(date) from public, anon, authenticated;

-- ── 운영자: 한 주의 응모 목록 (+ 응모권 수) — 돌려주는 열이 바뀌어 지우고 다시 만듦 ──
drop function if exists public.admin_event_week(date);
create function public.admin_event_week(w date)
returns table (entry_id bigint, code text, created_at timestamptz, is_member boolean, nickname text, email text,
               place_name text, body text, valid boolean, won text, tickets int, valid_tickets int, places text)
language plpgsql stable security definer set search_path = pg_catalog, public, pg_temp as $$
begin
  if not public.is_admin() then raise exception '운영자만 볼 수 있어요'; end if;
  return query
    select e.id, e.code, e.created_at, public.ppx_is_member(e.user_id),
           coalesce(pr.nickname, c.nickname), case when public.ppx_is_member(e.user_id) then u.email::text end,
           pl.name, c.body, public.ppx_entry_valid(e),
           (select x.pool from public.event_winners x where x.entry_id = e.id),
           (select count(*)::int from public.event_tickets t where t.entry_id = e.id),
           public.ppx_entry_weight(e),
           (select string_agg(coalesce(p2.name, '?') || case when c2.hidden then '(숨김)' else '' end, ', ' order by t.day)
              from public.event_tickets t
              left join public.place_comments c2 on c2.id = t.comment_id
              left join public.places p2 on p2.id = t.place_id
              where t.entry_id = e.id)
    from public.event_entries e
    left join public.profiles pr on pr.id = e.user_id
    left join auth.users u on u.id = e.user_id
    left join public.place_comments c on c.id = e.comment_id
    left join public.places pl on pl.id = c.place_id
    where e.week = w
    order by e.created_at;
end $$;
revoke all on function public.admin_event_week(date) from public, anon, authenticated;
grant execute on function public.admin_event_week(date) to authenticated;

-- ── 가입하면 기기에서 남긴 기록을 계정으로 옮김 (응모권 합치기) ──
create or replace function public.finish_claim(t uuid)
returns int language plpgsql security definer set search_path = pg_catalog, public, pg_temp as $$
declare a uuid; n int := 0; k int; ae record; de public.event_entries;
begin
  if auth.uid() is null or coalesce((auth.jwt()->>'is_anonymous')::boolean, false) then return 0; end if;
  delete from public.anon_claims where token = t returning anon_id into a;
  if a is null or a = auth.uid() then return 0; end if;
  update public.places set submitted_by = auth.uid() where submitted_by = a;        get diagnostics k = row_count; n := n + k;
  update public.place_reports set reporter = auth.uid() where reporter = a;         get diagnostics k = row_count; n := n + k;
  update public.place_comments set user_id = auth.uid() where user_id = a;          get diagnostics k = row_count; n := n + k;
  -- 같은 날 같은 세차장을 두 번 확인한 기록은 하나만 남김
  delete from public.place_checks c where c.user_id = a and exists (
    select 1 from public.place_checks d where d.user_id = auth.uid() and d.place_id = c.place_id and d.created_on = c.created_on);
  update public.place_checks set user_id = auth.uid() where user_id = a;            get diagnostics k = row_count; n := n + k;
  -- 기프티콘 응모: 같은 주에 계정 응모가 있으면 기기 쪽 응모권을 계정 응모로 합침
  --   (같은 날·같은 세차장은 1장만, 합쳐서 최대 3장) 그다음 기기 쪽 응모는 지움
  for ae in select * from public.event_entries where user_id = a loop
    select * into de from public.event_entries where user_id = auth.uid() and week = ae.week;
    if found then
      insert into public.event_tickets (entry_id, day, comment_id, place_id, created_at)
        select de.id, x.day, x.comment_id, x.place_id, x.created_at
        from public.event_tickets x
        where x.entry_id = ae.id
          and not exists (select 1 from public.event_tickets y where y.entry_id = de.id and (y.day = x.day or y.place_id = x.place_id))
        order by x.created_at
        limit greatest(0, public.ppx_event_max_tickets() - (select count(*) from public.event_tickets z where z.entry_id = de.id))
        on conflict do nothing;
      delete from public.event_entries where id = ae.id;
    end if;
  end loop;
  update public.event_entries set user_id = auth.uid() where user_id = a;           get diagnostics k = row_count; n := n + k;
  -- 종류 투표: 계정으로 이미 30일 안에 같은 세차장에 표가 있으면 기기 쪽 표는 정리
  delete from public.place_type_votes x where x.user_id = a and exists (
    select 1 from public.place_type_votes d where d.user_id = auth.uid() and d.place_id = x.place_id
      and d.created_at > now() - interval '30 days');
  update public.place_type_votes set user_id = auth.uid() where user_id = a;        get diagnostics k = row_count; n := n + k;
  return n;
end $$;
revoke all on function public.finish_claim(uuid) from public, anon, authenticated;
grant execute on function public.finish_claim(uuid) to authenticated;

commit;
