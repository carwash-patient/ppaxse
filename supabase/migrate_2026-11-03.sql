-- 1) 제보가 들어온 곳: 'map'(지도) / 'review'(후기 페이지)
alter table public.place_reports add column if not exists via text not null default 'map'
  check (via in ('map', 'review'));

-- 2) 한마디: 세차장마다 여러 사람이 짧게 남김. 바로 보이고, 운영자가 숨길 수 있음
create table if not exists public.place_comments (
  id          bigint generated by default as identity primary key,
  place_id    bigint not null references public.places(id) on delete cascade,
  user_id     uuid references public.profiles(id) on delete set null,
  nickname    text check (char_length(nickname) between 1 and 20),
  body        text not null check (char_length(body) between 1 and 200),
  hidden      boolean not null default false,
  created_at  timestamptz not null default now()
);
create index if not exists place_comments_place_idx on public.place_comments (place_id, created_at desc);
create index if not exists place_comments_user_idx  on public.place_comments (user_id, created_at);

-- 도배 방지 규칙에 한마디(하루 20개) 추가
create or replace function public.ppx_guard(what text)
returns void language plpgsql stable security definer set search_path = public as $$
declare n int; lim int;
begin
  if exists (select 1 from public.profiles where id = auth.uid() and blocked) then
    raise exception '이 기기에서는 지금 보낼 수 없어요. 문제가 있다면 운영자에게 알려주세요.';
  end if;
  if what = 'report' then
    lim := 30; select count(*) into n from public.place_reports where reporter = auth.uid() and created_at > now() - interval '1 day';
  elsif what = 'place' then
    lim := 10; select count(*) into n from public.places where submitted_by = auth.uid() and created_at > now() - interval '1 day';
  elsif what = 'comment' then
    lim := 20; select count(*) into n from public.place_comments where user_id = auth.uid() and created_at > now() - interval '1 day';
  else
    lim := 100; select count(*) into n from public.place_checks where user_id = auth.uid() and created_at > now() - interval '1 day';
  end if;
  if n >= lim then
    raise exception '오늘은 더 보낼 수 없어요. 내일 다시 부탁드려요.';
  end if;
end $$;

create or replace function public.place_comments_before_insert()
returns trigger language plpgsql as $$
begin
  if current_user not in ('anon', 'authenticated') then return new; end if;
  new.user_id    := auth.uid();
  new.hidden     := false;
  new.created_at := now();
  new.body       := btrim(new.body);
  new.nickname   := nullif(btrim(coalesce(new.nickname, '')), '');
  perform public.ppx_guard('comment');
  return new;
end $$;
drop trigger if exists place_comments_before_insert on public.place_comments;
create trigger place_comments_before_insert before insert on public.place_comments
  for each row execute function public.place_comments_before_insert();

alter table public.place_comments enable row level security;
drop policy if exists "comments: 조회" on public.place_comments;
create policy "comments: 조회" on public.place_comments
  for select using (not hidden or user_id = auth.uid() or public.is_admin());
drop policy if exists "comments: 쓰기" on public.place_comments;
create policy "comments: 쓰기" on public.place_comments
  for insert to authenticated
  with check (exists (select 1 from public.places p where p.id = place_id and p.status = 'approved'));
drop policy if exists "comments: 운영자 숨기기" on public.place_comments;
create policy "comments: 운영자 숨기기" on public.place_comments
  for update using (public.is_admin()) with check (public.is_admin());
drop policy if exists "comments: 운영자 삭제" on public.place_comments;
create policy "comments: 운영자 삭제" on public.place_comments
  for delete using (public.is_admin());
-- 한마디를 쓴 사람이 누군지(user_id)는 운영자만 알면 되므로 일반 조회에서는 감춤
revoke select, insert, update, delete on public.place_comments from anon, authenticated;
grant select (id, place_id, nickname, body, hidden, created_at) on public.place_comments to anon, authenticated;
grant insert (place_id, nickname, body) on public.place_comments to authenticated;
grant update (hidden) on public.place_comments to authenticated;

-- 3) 후기 페이지 첫 화면의 "지금까지 ○○개의 정보가 모였어요"
create or replace function public.ppx_stats()
returns json language sql stable security definer set search_path = public as $$
  select json_build_object(
    'places',   (select count(*) from public.places where status = 'approved'),
    'reports',  (select count(*) from public.place_reports),
    'comments', (select count(*) from public.place_comments where not hidden),
    'checks',   (select count(*) from public.place_checks)
  );
$$;
grant execute on function public.ppx_stats() to anon, authenticated;

-- 4) 운영자: 한마디를 쓴 사람(기기)의 제보·한마디 막기 (쓴 사람 번호는 보여주지 않고 함수 안에서 처리)
create or replace function public.admin_block_commenter(cid bigint)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception '운영자만 할 수 있어요'; end if;
  update public.profiles set blocked = true
  where id = (select user_id from public.place_comments where id = cid) and role <> 'admin';
  update public.place_comments set hidden = true
  where user_id = (select user_id from public.place_comments where id = cid);
end $$;
revoke execute on function public.admin_block_commenter(bigint) from anon;
