-- 1) 세차장 추가 정보 + 확인 기록
--    info 예: {"hotwater":true,"vacuum":true,"bays":6,"pay":["card","coin"],"pw":3000,"pm":5,"brush":false,"height":"2.1m","svc":["coat"]}
alter table public.places add column if not exists info jsonb not null default '{}'::jsonb;
alter table public.places drop constraint if exists places_info_check;
alter table public.places add constraint places_info_check
  check (jsonb_typeof(info) = 'object' and octet_length(info::text) <= 1000);
alter table public.places add column if not exists checked_at timestamptz;          -- 마지막으로 '정보가 맞아요'를 누른 때
alter table public.places add column if not exists check_count int not null default 0;

-- 2) 회원: 제보 막기 (장난 제보 반복 시 운영자가 설정)
alter table public.profiles add column if not exists blocked boolean not null default false;

-- 3) 제보: 언제 가봤는지 + 가격표 사진
alter table public.place_reports add column if not exists visit text
  check (visit in ('today','week','month','older','none'));
alter table public.place_reports add column if not exists photo text
  check (char_length(photo) <= 200);
alter table public.place_reports drop constraint if exists place_reports_suggest_check;
alter table public.place_reports add constraint place_reports_suggest_check
  check (jsonb_typeof(suggest) = 'object' and octet_length(suggest::text) <= 3000);

-- 4) 도배 방지: 막힌 사람 · 하루 개수 제한 (가입 없이 쓰는 사람도 기기마다 따로 셈)
create or replace function public.ppx_guard(what text)
returns void language plpgsql stable security definer set search_path = public as $$
declare n int; lim int;
begin
  if exists (select 1 from public.profiles where id = auth.uid() and blocked) then
    raise exception '이 기기에서는 지금 보낼 수 없어요. 문제가 있다면 운영자에게 알려주세요.';
  end if;
  if what = 'report' then
    lim := 30; select count(*) into n from public.place_reports where reporter = auth.uid() and created_at > now() - interval '1 day';
  elsif what = 'place' then
    lim := 10; select count(*) into n from public.places where submitted_by = auth.uid() and created_at > now() - interval '1 day';
  else
    lim := 100; select count(*) into n from public.place_checks where user_id = auth.uid() and created_at > now() - interval '1 day';
  end if;
  if n >= lim then
    raise exception '오늘은 더 보낼 수 없어요. 내일 다시 부탁드려요.';
  end if;
end $$;

-- 5) '정보가 맞아요' 기록 (한 사람이 한 세차장에 하루 한 번)
create table if not exists public.place_checks (
  id          bigint generated by default as identity primary key,
  place_id    bigint not null references public.places(id) on delete cascade,
  user_id     uuid references public.profiles(id) on delete set null,
  created_on  date not null default current_date,
  created_at  timestamptz not null default now()
);
create unique index if not exists place_checks_once_idx on public.place_checks (place_id, user_id, created_on);
create index if not exists place_checks_user_idx on public.place_checks (user_id, created_at);

create or replace function public.place_checks_before_insert()
returns trigger language plpgsql as $$
begin
  if current_user not in ('anon', 'authenticated') then return new; end if;
  new.user_id := auth.uid();
  new.created_on := current_date;
  new.created_at := now();
  perform public.ppx_guard('check');
  return new;
end $$;
drop trigger if exists place_checks_before_insert on public.place_checks;
create trigger place_checks_before_insert before insert on public.place_checks
  for each row execute function public.place_checks_before_insert();

-- 확인하면 세차장의 '최근 확인'과 횟수를 올림 (일반 사용자는 places를 못 고치므로 security definer)
create or replace function public.place_checks_after_insert()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  update public.places set checked_at = new.created_at, check_count = check_count + 1 where id = new.place_id;
  return new;
end $$;
drop trigger if exists place_checks_after_insert on public.place_checks;
create trigger place_checks_after_insert after insert on public.place_checks
  for each row execute function public.place_checks_after_insert();

alter table public.place_checks enable row level security;
drop policy if exists "checks: 조회" on public.place_checks;
create policy "checks: 조회" on public.place_checks
  for select using (user_id = auth.uid() or public.is_admin());
drop policy if exists "checks: 확인" on public.place_checks;
create policy "checks: 확인" on public.place_checks
  for insert to authenticated
  with check (exists (select 1 from public.places p where p.id = place_id and p.status = 'approved'));

-- 6) 추가 요청·제보에도 막기·하루 제한 적용
create or replace function public.places_before_insert()
returns trigger language plpgsql as $$
begin
  if current_user not in ('anon', 'authenticated') or public.is_admin() then
    return new;
  end if;
  new.status        := 'pending';
  new.source        := 'user';
  new.submitted_by  := auth.uid();
  new.source_ref    := null;
  new.owner_id      := null;
  new.reviewed_by   := null;
  new.reviewed_at   := null;
  new.reject_reason := null;
  new.checked_at    := null;
  new.check_count   := 0;
  perform public.ppx_guard('place');
  if public.my_pending_count() >= 5 then
    raise exception '확인을 기다리는 요청이 5개 있어요. 처리된 뒤에 다시 요청해 주세요.';
  end if;
  return new;
end $$;

create or replace function public.place_reports_before_insert()
returns trigger language plpgsql as $$
begin
  if current_user not in ('anon', 'authenticated') then
    return new;
  end if;
  new.reporter    := auth.uid();
  new.status      := 'pending';
  new.reviewed_by := null;
  new.reviewed_at := null;
  if new.photo is not null and new.photo not like auth.uid()::text || '/%' then
    raise exception '사진 정보가 올바르지 않아요';
  end if;
  perform public.ppx_guard('report');
  if public.my_pending_reports() >= 10 then
    raise exception '확인을 기다리는 제보가 10개 있어요. 처리된 뒤에 다시 보내 주세요.';
  end if;
  return new;
end $$;

-- 7) 운영자: 제보 막기/풀기
create or replace function public.admin_block(uid uuid, on_off boolean)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception '운영자만 할 수 있어요'; end if;
  update public.profiles set blocked = on_off where id = uid and role <> 'admin';
end $$;
revoke execute on function public.admin_block(uuid, boolean) from anon;

-- 8) 가입 없이 쓰던 기기 → 가입/로그인하면 그동안의 요청·제보·확인을 계정으로 옮김
--    (가입 없이 쓰는 동안 받은 1회용 번호를 가진 기기만 옮길 수 있음)
create table if not exists public.anon_claims (
  token      uuid primary key default gen_random_uuid(),
  anon_id    uuid not null,
  created_at timestamptz not null default now()
);
alter table public.anon_claims enable row level security;   -- 정책 없음 = 앱에서 직접 못 봄

create or replace function public.start_claim()
returns uuid language plpgsql security definer set search_path = public as $$
declare t uuid;
begin
  if auth.uid() is null or coalesce((auth.jwt()->>'is_anonymous')::boolean, false) is not true then
    return null;
  end if;
  delete from public.anon_claims where anon_id = auth.uid() or created_at < now() - interval '30 days';
  insert into public.anon_claims (anon_id) values (auth.uid()) returning token into t;
  return t;
end $$;

create or replace function public.finish_claim(t uuid)
returns int language plpgsql security definer set search_path = public as $$
declare a uuid; n int := 0; k int;
begin
  if auth.uid() is null or coalesce((auth.jwt()->>'is_anonymous')::boolean, false) then return 0; end if;
  delete from public.anon_claims where token = t returning anon_id into a;
  if a is null or a = auth.uid() then return 0; end if;
  update public.places set submitted_by = auth.uid() where submitted_by = a;        get diagnostics k = row_count; n := n + k;
  update public.place_reports set reporter = auth.uid() where reporter = a;         get diagnostics k = row_count; n := n + k;
  -- 같은 날 같은 세차장을 두 번 확인한 기록은 하나만 남김
  delete from public.place_checks c where c.user_id = a and exists (
    select 1 from public.place_checks d where d.user_id = auth.uid() and d.place_id = c.place_id and d.created_on = c.created_on);
  update public.place_checks set user_id = auth.uid() where user_id = a;            get diagnostics k = row_count; n := n + k;
  return n;
end $$;
revoke execute on function public.start_claim() from anon;
revoke execute on function public.finish_claim(uuid) from anon;

